#!/bin/bash
# run_incident_audit.sh - Complete the post-rollback audit trail for a rolled-back service.
# Usage: run_incident_audit.sh <service>
#
# Runs the post-rollback audit required by IR-RUNBOOK-003 (health checks recomputed from state,
# recorded as an audit entry) and writes the audit report. Records audit_status=COMPLETE.
set -euo pipefail
SERVICE="${1:-}"
REPORTS_DIR="/workspace/reports"; mkdir -p "$REPORTS_DIR"
STATE="/workspace/monitoring/deploy_state.json"
if [ -z "$SERVICE" ]; then echo "ERROR: Service name required"; echo "Usage: run_incident_audit.sh <service>"; exit 1; fi
TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
# Re-invoke the rollback engine on the already-rolled-back service (skip=0): it detects the
# outstanding audit and runs it now -> audit_status=COMPLETE + audit record.
python3 /workspace/scripts/_rollback_engine.py "$SERVICE" 0
AUDIT_STATUS=$(python3 -c "import json;print(json.load(open('$STATE'))['services'].get('$SERVICE',{}).get('audit_status','NONE'))" 2>/dev/null || echo "NONE")
if [ "$AUDIT_STATUS" = "COMPLETE" ]; then
    AUDIT_REPORT="${REPORTS_DIR}/rollback_audit_${SERVICE}.md"
    python3 - "$SERVICE" "$TIMESTAMP" "$AUDIT_REPORT" <<'PY'
import json, sys
service, ts, out = sys.argv[1:4]
svc = json.load(open("/workspace/monitoring/deploy_state.json"))["services"][service]
audit = svc.get("last_audit") or {}
checks = audit.get("checks", {})
rows = "\n".join(f"| {k.replace('_',' ')} | {'PASS' if v else 'FAIL'} |" for k, v in checks.items())
open(out, "w").write(f"""# Post-Rollback Audit Report

**Service:** {service}
**Timestamp:** {ts}
**Now running:** {svc.get('current_version')}
**Audit verdict:** {audit.get('verdict','(none)')}

## Health Check Results (recomputed from deployment state)

| Check | Status |
|-------|--------|
{rows}

---
*Generated by run_incident_audit.sh from deploy_state.json | IR-RUNBOOK-003*
""")
print(f"  Audit report saved to: {out}")
PY
    echo "${TIMESTAMP} | AUDIT | service=${SERVICE} | AUDIT_COMPLETE" >> /workspace/logs/deploy_history.log
fi
